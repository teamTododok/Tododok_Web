const suit = { fontFamily: "SUIT, sans-serif" };
const base = { ...suit, fontSize: 14, lineHeight: "160%", color: "#1A1A1A" } as const;

type Line =
  | { type: "body"; text: string; spacingBefore?: boolean }
  | { type: "h1"; text: string }
  | { type: "num1"; label: string; text: string; spacingBefore?: boolean }
  | { type: "num2"; label: string; text: string; spacingBefore?: boolean }

function Article({ lines }: { lines: Line[] }) {
  return (
    <div style={{ display: "flex", flexDirection: "column" }}>
      {lines.map((line, i) => {
        const mt = line.type !== "h1" && line.spacingBefore ? 10 : i === 0 ? 0 : 2;
        if (line.type === "h1") {
          return (
            <p key={i} style={{ ...base, fontWeight: 700, margin: 0, marginBottom: i === 0 ? 2 : 0, marginTop: i === 0 ? 0 : 4 }}>
              {line.text}
            </p>
          );
        }
        if (line.type === "num1") {
          return (
            <div key={i} style={{ display: "flex", marginTop: mt }}>
              <span style={{ ...base, fontWeight: 400, flexShrink: 0, minWidth: 22 }}>{line.label}</span>
              <p style={{ ...base, fontWeight: 400, margin: 0, marginLeft: 4 }}>{line.text}</p>
            </div>
          );
        }
        if (line.type === "num2") {
          return (
            <div key={i} style={{ display: "flex", marginTop: mt, paddingLeft: 18 }}>
              <span style={{ ...base, fontWeight: 400, flexShrink: 0, minWidth: 28 }}>{line.label}</span>
              <p style={{ ...base, fontWeight: 400, margin: 0, marginLeft: 4 }}>{line.text}</p>
            </div>
          );
        }
        return (
          <p key={i} style={{ ...base, fontWeight: 400, margin: 0, marginTop: mt }}>
            {line.text}
          </p>
        );
      })}
    </div>
  );
}

